#ifndef PROPHECY_MINHEAP_H
    #define PROPHECY_MINHEAP_H
    #include <stdbool.h>
    #include <stddef.h>

///////////////////////////////////////////////////////////////////////////////
/**
 * @brief  Forward declaration of kfScheduler
 */
///////////////////////////////////////////////////////////////////////////////
typedef struct prophecy_scheduler_s kfScheduler;
///////////////////////////////////////////////////////////////////////////////


///////////////////////////////////////////////////////////////////////////////
/**
 * @brief  Forward declaration of kfTask
 */
///////////////////////////////////////////////////////////////////////////////
typedef struct prophecy_task_s      kfTask;
///////////////////////////////////////////////////////////////////////////////


///////////////////////////////////////////////////////////////////////////////
/**
 * @brief  Heap order: earliest target first, then lowest id
 *
 * @param a  The first task
 * @param b  The second task
 * @return   true if a must run before b
 */
///////////////////////////////////////////////////////////////////////////////
bool prMinHeap_less(const kfTask *a, const kfTask *b);
///////////////////////////////////////////////////////////////////////////////


///////////////////////////////////////////////////////////////////////////////
/**
 * @brief  Bubble up the task at index in scheduler array
 *
 * @param sch  The scheduler
 * @param idx  The index of the task
 */
///////////////////////////////////////////////////////////////////////////////
void prMinHeap_add(kfScheduler *sch, size_t idx);
///////////////////////////////////////////////////////////////////////////////


///////////////////////////////////////////////////////////////////////////////
/**
 * @brief  Bubble down the task to remove it
 *
 * @param sch  The scheduler where the task to remove if
 * @param idx  The index of the task to remove
 */
///////////////////////////////////////////////////////////////////////////////
void prMinHeap_remove(kfScheduler *sch, size_t idx);
///////////////////////////////////////////////////////////////////////////////


///////////////////////////////////////////////////////////////////////////////
/**
 * @brief  Swap two tasks
 *
 * @param task1  The task1 to swap
 * @param task2  The task2 to swap
 */
///////////////////////////////////////////////////////////////////////////////
void prMinHeap_swap(kfTask *task1, kfTask *task2);
///////////////////////////////////////////////////////////////////////////////

#endif /* PROPHECY_MINHEAP_H */
