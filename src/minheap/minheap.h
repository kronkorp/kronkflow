#ifndef PROPHECY_MINHEAP_H
    #define PROPHECY_MINHEAP_H
    #include <stddef.h>

///////////////////////////////////////////////////////////////////////////////
/**
 * @brief  Forward declaration of prScheduler
 */
///////////////////////////////////////////////////////////////////////////////
typedef struct prophecy_scheduler_s prScheduler;
///////////////////////////////////////////////////////////////////////////////


///////////////////////////////////////////////////////////////////////////////
/**
 * @brief  Forward declaration of prTask
 */
///////////////////////////////////////////////////////////////////////////////
typedef struct prophecy_task_s      prTask;
///////////////////////////////////////////////////////////////////////////////


///////////////////////////////////////////////////////////////////////////////
/**
 * @brief  Bubble up the task at index in scheduler array
 *
 * @param sch  The scheduler
 * @param idx  The index of the task
 */
///////////////////////////////////////////////////////////////////////////////
void prMinHeap_add(prScheduler *sch, size_t idx);
///////////////////////////////////////////////////////////////////////////////


///////////////////////////////////////////////////////////////////////////////
/**
 * @brief  Bubble down the task to remove it
 *
 * @param sch  The scheduler where the task to remove if
 * @param idx  The index of the task to remove
 */
///////////////////////////////////////////////////////////////////////////////
void prMinHeap_remove(prScheduler *sch, size_t idx);
///////////////////////////////////////////////////////////////////////////////


///////////////////////////////////////////////////////////////////////////////
/**
 * @brief  Swap two tasks
 *
 * @param task1  The task1 to swap
 * @param task2  The task2 to swap
 */
///////////////////////////////////////////////////////////////////////////////
void prMinHeap_swap(prTask *task1, prTask *task2);
///////////////////////////////////////////////////////////////////////////////

#endif /* PROPHECY_MINHEAP_H */
